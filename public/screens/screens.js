/* The visitor's current time, like an Android status bar: their 12 or 24 hour
   setting, without AM/PM. Updates on the minute. */
function statusTime(date = new Date()) {
  return new Intl.DateTimeFormat(undefined, { hour: 'numeric', minute: '2-digit' })
    .formatToParts(date)
    .filter((p) => p.type !== 'dayPeriod')
    .map((p) => p.value)
    .join('')
    .trim()
}
const clock = document.querySelector('[data-clock]')
const tick = () => {
  clock.textContent = statusTime()
  setTimeout(tick, 60000 - (Date.now() % 60000) + 50)
}
tick()

/** Replaces each <i data-icon="name"> with its SVG. */
document.querySelectorAll('i[data-icon]').forEach((el) => {
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg')
  svg.setAttribute('viewBox', '0 0 24 24')
  svg.setAttribute('class', `ic ${el.className}`.trim())
  svg.setAttribute('aria-hidden', 'true')
  const path = document.createElementNS('http://www.w3.org/2000/svg', 'path')
  path.setAttribute('d', ICONS[el.dataset.icon])
  svg.append(path)
  el.replaceWith(svg)
})

/* Letter avatars: same palette and sizing as LetterAvatar. */
document.querySelectorAll('.avatar').forEach((el) => {
  const size = Number(el.dataset.size || 40)
  const color = el.dataset.color
  Object.assign(el.style, {
    width: `${size}px`,
    height: `${size}px`,
    borderRadius: `${size * 0.28}px`,
    fontSize: `${size * 0.42}px`,
    color,
    background: `color-mix(in srgb, ${color} 14%, transparent)`,
  })
})

/* Theme: follow the embedding page live; standalone uses ?theme= or dark. */
const applyTheme = () => {
  let theme = new URLSearchParams(location.search).get('theme') || 'dark'
  try {
    if (window.parent !== window) theme = window.parent.document.documentElement.dataset.theme || theme
  } catch {
    // Embedded from another origin: keep the query/default theme.
  }
  document.documentElement.dataset.theme = theme
}
applyTheme()
try {
  if (window.parent !== window) {
    new MutationObserver(applyTheme).observe(window.parent.document.documentElement, {
      attributes: true,
      attributeFilter: ['data-theme'],
    })
  }
} catch {
  // Cross-origin parent: no live theme sync.
}
